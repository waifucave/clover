// The core's view types a plugin's parts read (a bot, a session, a computer, a plugin's record…), written as plain
// TypeScript into `src/views.ts` from the core's own schemas, so the SDK's published types stand alone (the protocol
// package is not published). `bun run generate` writes it; a test checks it is current.
import { z } from "zod";
import * as Proto from "@waifucave/moss-protocol";

/** The views, by the name the SDK exports them under. */
export const VIEWS: Readonly<Record<string, z.ZodType>> = {
  BotView: Proto.BotView,
  SessionView: Proto.SessionView,
  ArchivedSessionView: Proto.ArchivedSessionView,
  ComputerView: Proto.ComputerView,
  DeviceView: Proto.DeviceView,
  PluginSummary: Proto.PluginSummary,
  PluginDetail: Proto.PluginDetail,
  IndexView: Proto.IndexView,
  IndexEntryView: Proto.IndexEntryView,
  CardMeta: Proto.CardMeta,
  SessionKind: Proto.SessionKind,
  FileStat: Proto.FileStat,
  UiPluginView: Proto.UiPluginView,
  UiSettings: Proto.UiSettings,
};

type Schema = {
  type?: string | string[];
  properties?: Record<string, Schema>;
  required?: string[];
  additionalProperties?: boolean | Schema;
  items?: Schema | Schema[];
  prefixItems?: Schema[];
  enum?: unknown[];
  const?: unknown;
  anyOf?: Schema[];
  oneOf?: Schema[];
  allOf?: Schema[];
  $ref?: string;
  $defs?: Record<string, Schema>;
  description?: string;
  propertyNames?: Schema;
};

const KEY = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function emit(s: Schema, indent: string, defs: Record<string, Schema>, seen: Set<string>): string {
  if (s.$ref !== undefined) {
    const name = s.$ref.replace(/^#\/(\$defs|definitions)\//, "");
    if (s.$ref === "#") return "unknown";
    if (seen.has(name)) return "unknown";
    const def = defs[name];
    return def === undefined ? "unknown" : emit(def, indent, defs, new Set([...seen, name]));
  }
  if (s.const !== undefined) return JSON.stringify(s.const);
  if (s.enum !== undefined) return s.enum.map((v) => JSON.stringify(v)).join(" | ");
  const union = s.anyOf ?? s.oneOf;
  if (union !== undefined) return [...new Set(union.map((u) => wrap(emit(u, indent, defs, seen))))].join(" | ");
  if (s.allOf !== undefined) return s.allOf.map((u) => wrap(emit(u, indent, defs, seen))).join(" & ");
  const type = s.type;
  if (Array.isArray(type)) return type.map((t) => emit({ ...s, type: t }, indent, defs, seen)).join(" | ");
  switch (type) {
    case "string": return "string";
    case "number": case "integer": return "number";
    case "boolean": return "boolean";
    case "null": return "null";
    case "array": {
      if (s.prefixItems !== undefined) return `[${s.prefixItems.map((i) => emit(i, indent, defs, seen)).join(", ")}]`;
      const item = Array.isArray(s.items) ? { anyOf: s.items } : s.items;
      return item === undefined ? "unknown[]" : `${wrap(emit(item, indent, defs, seen))}[]`;
    }
    case "object": {
      const props = s.properties ?? {};
      const req = new Set(s.required ?? []);
      const inner = indent + "  ";
      const lines = Object.entries(props).map(([k, v]) => {
        const doc = v.description !== undefined ? `${inner}/** ${v.description.replace(/\*\//g, "* /")} */\n` : "";
        return `${doc}${inner}${KEY.test(k) ? k : JSON.stringify(k)}${req.has(k) ? "" : "?"}: ${emit(v, inner, defs, seen)};`;
      });
      const extra = s.additionalProperties;
      if (extra !== undefined && extra !== false) lines.push(`${inner}[key: string]: ${extra === true ? "unknown" : emit(extra, inner, defs, seen)};`);
      if (lines.length === 0) return extra === false ? "Record<string, never>" : "Record<string, unknown>";
      return `{\n${lines.join("\n")}\n${indent}}`;
    }
    default: return "unknown";
  }
}

const wrap = (t: string) => (/[|&]/.test(t) && !t.startsWith("{") ? `(${t})` : t);

/** One schema as a plain TypeScript type (its text). */
export function typeOf(schema: z.ZodType): string {
  const json = z.toJSONSchema(schema, { io: "output", unrepresentable: "any" }) as Schema;
  return emit(json, "", json.$defs ?? {}, new Set());
}

/** The file's text. */
export function viewsSource(): string {
  const out = [
    "// GENERATED by scripts/views.ts (`bun run generate`) from the core's schemas: do not edit. The core's views a plugin's",
    "// parts read, as plain types (the SDK's published types depend on no unpublished package).",
    "",
  ];
  for (const [name, schema] of Object.entries(VIEWS)) {
    const json = z.toJSONSchema(schema, { io: "output", unrepresentable: "any" }) as Schema;
    out.push(`export type ${name} = ${emit(json, "", json.$defs ?? {}, new Set())};`, "");
  }
  return out.join("\n");
}

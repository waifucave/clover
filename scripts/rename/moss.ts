// `codemod.ts` runs (`--rules moss`, the default); Winter→Clover (`clover.ts`) and Norma→Winter (`allowlist.ts`) stay
// beside it as the records of those renames, with their residue tests.
//
// THE NAMES (the owner's rulings)
//   * Prose and UI text say MOSS (all capitals): "MOSS's window", "MOSS Voice". Ids, paths, package names, URL schemes and
//     every lower-case use say `moss`. Env prefix `MOSS_`.
//   * THE SHAPE RULE (`mossGeneric`): a generic `Clover` that touches an identifier character on either side
//     (`CloverClient`, `buildCloverOptions`, `Clover_x`, `Clover2`) is part of a code token and becomes `Moss`
//     (`MossClient`, `buildMossOptions`); a `Clover` that stands alone as a word (prose, a UI string, a comment, a markdown
//     heading, a possessive: `Clover's`) becomes `MOSS`. A `\nClover` in a string literal is a word after an escape, so the
//     letter before it does not count. `clover` is always `moss` (`cloverHome` → `mossHome`, `clover-core` → `moss-core`),
//     `CLOVER` always `MOSS` (`CLOVER_HOME` → `MOSS_HOME`). A path component takes the same rule on its own text.
//   * THE APP is "MOSS Code" and only its own identity takes that name (`MOSS_REGEX_MAP`): the bundle `MOSS Code.app`, the dev
//     build `MOSS Code Dev`, `MOSS Code.exe`, the installer and archive names `MOSS-Code-<version>…`, the Linux install
//     folder `/opt/moss-code/` (never a space on Linux) and the app id `com.waifucave.moss.code` (+ `.dev`). The engine's ids are
//     `com.waifucave.moss.core…` (its Keychain service and launch-agent label `com.waifucave.moss.core`). The bare
//     `com.waifucave.moss` is never produced: a second app takes it later.
//
// WHAT THE PASS LEAVES (every one is an allowlist entry or an exempt path below, and `moss-residue.test.ts` fails on any other)
//   * names another repo or the registry defines: the agent SDK's packages (`@waifucave/clover-agent-sdk` and its siblings,
//     published from the `clover-sdk` repo, installed from GitHub Packages) and its `clover/load` result key; the iOS app's
//     own repo and bundle id;
//   * names a USER wrote on disk outside the home, read by the one old-name helper (`packages/core/src/old-names.ts`): a
//     project's `.clover/` folder, a `CLOVER.md`, a folder plugin's `clover.json`;
//   * the plant: Alpha's meadow art draws clovers (and the scene is called the "Clover meadow"), which is not the product;
//   * history: `releases/`, the release notes, `docs/research/`, `spikes/` (and their workflows), the kept Swift tree `apple/`,
//     Winter for Chrome, `infra/`; and what the generators rewrite (lockfiles).
// Adding an entry is a reviewed edit: the residue test fails on any `clover` no entry permits AND on any entry — or any
// top-level alternative of an entry's regex — that no longer matches anything.

/** The new name of a generic match (`codemod.ts` calls it for every `clover|Clover|CLOVER` that survives the earlier steps). */
export function mossGeneric(match: string, index: number, text: string): string {
  if (match === "clover") return "moss";
  if (match === "CLOVER") return "MOSS";
  const id = /[A-Za-z0-9_]/;
  const prev = text[index - 1] ?? "";
  const next = text[index + match.length] ?? "";
  const afterEscape = /[nrtbfv]/.test(prev) && text[index - 2] === "\\"; // `\nClover`: a word after an escape
  return (id.test(prev) && !afterEscape) || id.test(next) ? "Moss" : "MOSS";
}


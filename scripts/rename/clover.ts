// Clover C0 — the DATA behind the Winter→Clover rename (spec §2, §3.3, §12; plan §7). It is the
// second rule set `codemod.ts` runs (`--rules clover`, the default); the first, Norma→Winter, lives
// in `allowlist.ts` and stays as the record of Winter Phase 9b.
//
//   * `CLOVER_ALLOWLIST` — literals the codemod PROTECTS (placeholdered around both passes) and the
//     Clover residue test (`packages/core/test/rename/clover-residue.test.ts`) PERMITS afterwards.
//     Every entry names something this repo does not get to rename by editing itself: a package on
//     npm, a name another repo or a kept Swift target defines, a value already on the wire or on
//     disk, live infrastructure, or history.
//   * `CLOVER_EXPLICIT_TOKEN_MAP` — whole-token renames applied BEFORE the generic pass, where the
//     new name is not the old one with `winter` swapped for `clover`: the npm scope, the identities
//     (`com.winter.app` → `com.waifucave.clover`), the repo slugs.
//   * `CLOVER_EXEMPT_PATHS` — files the content pass never rewrites and the path pass never moves.
//
// Adding an entry is a reviewed edit: the residue test fails on any `winter` no entry permits AND on
// any entry that no longer matches anything.

/**
 * The compiled-binary proof that the Cowork native channel's receiver thread starts in the SHIPPED `clover-core`.
 *
 * `fd-channel.ts` serves every launcher channel from ONE Bun Worker. In dev it builds the Worker from an absolute source URL; in a compiled binary it must use the plain relative
 * string `./fd-receiver-worker.ts` (a `new URL(...).href` hangs silently, WS-23 spike #1), which resolves only if `packages/cli/src/fd-receiver-worker.ts` was passed to
 * `compile:core` as a third entrypoint. `bun test` only runs the dev path, so nothing but the real artifact notices that missing.
 *
 *   1. `compile:core` -> dist/clover-core (all five entrypoints: main, the two Worker files, the plugin host's two bundles), release-shaped: with a
 *      bundled-plugins manifest embedded as a release build embeds one (a file outside src/; compile:core's `--root src` keeps the Worker entries' names).
 *   2. A copy in a throwaway directory, ad-hoc signed the way the Release app signs clover-core (lib.ts's RESOURCE_BINARIES: hardened runtime and the `restrict`
 *      flag, scripts/clover-core.entitlements), so every step below runs restricted.
 *   3. `<copy> __fd-receiver-probe` from that directory, with a narrow environment and a temp CLOVER_HOME: socketpair, one line through the receiver hub, expect the line back.
 *   3b. `<copy> __host-code-adapter-probe`: the host-code broker's SDK modules resolve INSIDE the built binary (`installedHostCodeAdapter()` does not throw "Cannot find module").
 *       Same safety: no home, Keychain, daemon or launcher.
 *   3c. `<copy> __host-env-lazy-probe`: the activation seam's lazy `require("./host-env/environment")` resolves INSIDE the built binary (the seam stays off; the module loads, nothing is built).
 *   3d. (#234's checks 4 and 5) The release-shaped binary has no `__plugin-run-probe` route (`compile:core` defines `CLOVER_PLUGIN_RUN_PROBE=false`, and the route's code is
 *       not in it). A second build with the define true, with a dev `clover-plugin-bun` in the temp home's bin (a copy of this Bun, ad-hoc signed as
 *       `com.waifucave.clover.plugin-bun.dev`, its digest recorded beside it as dev:daemon records it), runs `<copy> __plugin-run-probe <empty folder>`: `pluginBun()` accepts that copy, and
 *       a plugin host started the supervisor's way runs on `clover-plugin-bun`, never on clover-core, as Bun (its `Bun.main` is
 *       the host's entry), without the `BUN_BE_BUN` it was handed, with the load guard preloaded (no `ShadowRealm`), and an outside import is refused and never runs.
 *       Same safety: the scratch folder only.
 *   3e. (lane M) The same probe build runs `<copy> __plugin-host-probe <empty folder>`: a plugin-host process starts the daemon's way (`hostProcessLaunch`,
 *       `spawnHostProcess`) from the bundles the core EMBEDS (a compiled core has no sources to build them from), byte for byte, on `clover-plugin-bun`, with the
 *       host guard preloaded (`host-guard.mjs` beside plugin-host.js, generated by the core) and leading its own process group, and answers
 *       `pluginHost.ping` over its fd-3 link. Same safety: the scratch folder only.
 *   4. (lane M) The `restrict` flag hides the environment: `<copy> __restrict-probe` (the probe build) and the plugin Bun running packages/cli/src/restrict-probe.ts, each signed
 *      as a release signs it, started with a dummy variable this script makes up. While each waits on its stdin, this script (another process of the same user) reads its
 *      arguments and environment through sysctl KERN_PROCARGS2: the dummy must not be there. The process itself saw it, and Bun.serve with fetch,
 *      and bun:ffi, worked. Whether a DYLD_ variable reached it is reported, not required: dyld strips them under the hardened runtime only with SIP on, and
 *      GitHub's macOS runners run with SIP off. The control: a copy signed with the hardened runtime alone, whose environment this same reader must see (or the reading proves nothing).
 *      Only true/false is printed, never a value; the dummy is random and no real variable is passed.
 *   5. The negative control: the same probe against a copy of the binary whose Worker entry cannot be found must NOT print ok. (Checked without rebuilding: the probe is run with the
 *      entry string patched in the copy to a name that does not exist.)
 *
 *   bun run verify:fd-receiver
 *
 * Standalone, never part of `bun test`. The probe touches no home, no Keychain, no daemon and no launcher, and the script never runs anything but the temp copy.
 */
import { spawn, spawnSync } from "node:child_process";
import { chmodSync, copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { homedir, tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { randomBytes } from "node:crypto";
import { RESTRICT_PROBE_DYLD_VARIABLE, RESTRICT_PROBE_VARIABLE, type RestrictProbeReady } from "../packages/cli/src/restrict-probe";
import { PLUGIN_BUN_IDENTIFIER as PLUGIN_BUN_IDENTIFIERS } from "../packages/core/src/bundled-identities";
import { pluginBunDigest } from "../packages/core/src/registry/plugin-run";
import { MANIFEST_EMBED } from "./build-daemon";
import { RESOURCE_BINARIES, signOptions } from "./release/lib";

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DIST_BINARY = join(REPO_ROOT, "dist", "clover-core");
const ENTITLEMENTS = join(REPO_ROOT, "scripts", "clover-core.entitlements");
const COMPILE_TIMEOUT_MS = 180_000, PROBE_TIMEOUT_MS = 30_000;
const CLI_DIR = join(REPO_ROOT, "packages", "cli");
const PLUGIN_BUN_ENTITLEMENTS = join(REPO_ROOT, "scripts", "clover-plugin-bun.entitlements");
const RESTRICT_PROBE_SCRIPT = join(CLI_DIR, "src", "restrict-probe.ts");
/** How a release signs the two (lib.ts's RESOURCE_BINARIES): this gate signs its copies the same way. */
const CORE_OPTIONS = signOptions(RESOURCE_BINARIES.find((b) => b.file === "clover-core")!);
const PLUGIN_BUN_OPTIONS = signOptions(RESOURCE_BINARIES.find((b) => b.file === "clover-plugin-bun")!);
/** The plugin Bun's dev signing identifier (`bundled-identities.ts`): never clover-core's. */
const PLUGIN_BUN_IDENTIFIER = PLUGIN_BUN_IDENTIFIERS.dev;
/** Strings only the plugin-run probe's code holds: absent from a release-shaped build. */
const PROBE_MARKERS = ["__plugin-run-probe", "the probe needs an absolute path to an empty scratch folder", "__plugin-host-probe", "the host probe needs an absolute path to an empty scratch folder", "__restrict-probe"];
export const ENTRY_NAME = "./fd-receiver-worker.ts";

/** The probe's one JSON line, or undefined. */
export function parseProbe(stdout: string): { ok: boolean; line?: string; error?: string } | undefined {
  for (const raw of stdout.split("\n")) {
    const text = raw.trim();
    if (!text.startsWith("{")) continue;
    try { const value = JSON.parse(text); if (typeof value?.ok === "boolean") return value; } catch { /* not the line */ }
  }
  return undefined;
}

/** A copy of the binary whose receiver entry string names a file that is not embedded (same length, so the executable layout is untouched). Null when the entry string is absent. */
export function withBrokenEntry(binary: Uint8Array): Buffer | null {
  const needle = Buffer.from(ENTRY_NAME), replacement = Buffer.from("./fd-receiver-wxrker.ts");
  const bytes = Buffer.from(binary);
  let at = bytes.indexOf(needle), count = 0;
  while (at >= 0) { replacement.copy(bytes, at); count += 1; at = bytes.indexOf(needle, at + needle.length); }
  return count > 0 ? bytes : null;
}

function runChild(binary: string, args: string[], env: Record<string, string>, cwd: string): Promise<{ code: number | null; stdout: string; stderr: string }> {
  return new Promise((resolve, reject) => {
    const child = spawn(binary, args, { stdio: ["ignore", "pipe", "pipe"], env, cwd });
    let stdout = "", stderr = "";
    child.stdout.on("data", (d: Buffer) => { stdout += d.toString("utf8"); });
    child.stderr.on("data", (d: Buffer) => { stderr += d.toString("utf8"); });
    const timer = setTimeout(() => { try { child.kill("SIGKILL"); } catch { /* gone */ } resolve({ code: null, stdout, stderr: `${stderr}\n(timed out after ${PROBE_TIMEOUT_MS} ms)` }); }, PROBE_TIMEOUT_MS);
    child.on("error", (error) => { clearTimeout(timer); reject(error); });
    child.on("close", (code) => { clearTimeout(timer); resolve({ code, stdout, stderr }); });
  });
}

function sign(path: string, options: string = CORE_OPTIONS): void {
  const result = spawnSync("codesign", ["--force", "--sign", "-", "--options", options, "--entitlements", ENTITLEMENTS, path], { encoding: "utf8" });
  if (result.status !== 0) throw new Error(`codesign of ${path} failed: ${(result.stderr ?? "").trim()}`);
}

/** A KERN_PROCARGS2 buffer's parts: `argc`, the executable path, padding, `argc` arguments, then the environment. */
export function procArgsParts(buf: Uint8Array): { argv: string[]; env: string[] } | undefined {
  if (buf.length < 4) return undefined;
  const argc = new DataView(buf.buffer, buf.byteOffset, buf.byteLength).getInt32(0, true);
  const strings: string[] = [];
  let at = 4;
  const next = (): string | undefined => {
    const end = buf.indexOf(0, at);
    if (end < 0) return undefined;
    const s = Buffer.from(buf.subarray(at, end)).toString("utf8");
    at = end + 1;
    return s;
  };
  if (next() === undefined) return undefined; // the executable path
  while (at < buf.length && buf[at] === 0) at += 1; // its padding
  for (let i = 0; i < argc; i++) {
    const s = next();
    if (s === undefined) return { argv: strings, env: [] };
    strings.push(s);
  }
  const env: string[] = [];
  while (at < buf.length && buf[at] !== 0) {
    const s = next();
    if (s === undefined) break;
    env.push(s);
  }
  return { argv: strings, env };
}

/** What another process of this user reads of `pid` through sysctl KERN_PROCARGS2 (what `ps -E` shows): whether the
 *  call answered, and whether `needle` is among its environment entries. */
export async function readsEnvironment(pid: number, needle: string): Promise<{ answered: boolean; env: boolean }> {
  const { dlopen, ptr } = await import("bun:ffi");
  const lib = dlopen("/usr/lib/libSystem.B.dylib", { sysctl: { args: ["ptr", "u32", "ptr", "ptr", "ptr", "usize"], returns: "i32" } });
  try {
    const mib = new Int32Array([1 /* CTL_KERN */, 49 /* KERN_PROCARGS2 */, pid]);
    const size = new BigUint64Array([0n]);
    if (lib.symbols.sysctl(ptr(mib), 3, null, ptr(size), null, 0) !== 0 || size[0] === 0n) return { answered: false, env: false };
    const buf = new Uint8Array(Number(size[0]));
    if (lib.symbols.sysctl(ptr(mib), 3, ptr(buf), ptr(size), null, 0) !== 0) return { answered: false, env: false };
    const parts = procArgsParts(buf.subarray(0, Number(size[0])));
    return { answered: parts !== undefined, env: parts?.env.includes(needle) ?? false };
  } finally {
    lib.close();
  }
}

/** Starts the restrict probe (`cmd`), with the dummy variable and a DYLD_ one, reads its environment from here while
 *  it waits, then ends it. Returns what it reported and what this process could read. */
export async function restrictRun(cmd: string[], env: Record<string, string>, cwd: string): Promise<{ ready?: RestrictProbeReady; read: { answered: boolean; env: boolean }; code: number | null; stderr: string }> {
  const dummy = `restrict-probe-${randomBytes(12).toString("hex")}`;
  const child = Bun.spawn(cmd, { cwd, env: { ...env, [RESTRICT_PROBE_VARIABLE]: dummy, [RESTRICT_PROBE_DYLD_VARIABLE]: "1" }, stdin: "pipe", stdout: "pipe", stderr: "pipe" });
  const timer = setTimeout(() => child.kill("SIGKILL"), PROBE_TIMEOUT_MS);
  let ready: RestrictProbeReady | undefined;
  let read = { answered: false, env: false };
  try {
    const reader = child.stdout.getReader();
    let text = "";
    while (!text.includes("\n")) {
      const { value, done } = await reader.read();
      if (done) break;
      text += new TextDecoder().decode(value);
    }
    reader.releaseLock();
    try { ready = JSON.parse(text.split("\n")[0] ?? "") as RestrictProbeReady; } catch { /* reported below */ }
    if (ready?.ready === true) read = await readsEnvironment(child.pid, `${RESTRICT_PROBE_VARIABLE}=${dummy}`);
  } finally {
    child.stdin.end();
  }
  const code = await child.exited;
  clearTimeout(timer);
  const stderr = (await new Response(child.stderr).text()).replaceAll(dummy, "<dummy>").trim().slice(0, 600);
  return { ...(ready !== undefined ? { ready } : {}), read, code, stderr };
}

const probeWorked = (r: Awaited<ReturnType<typeof restrictRun>>): boolean =>
  r.code === 0 && r.ready?.envSet === true && r.ready.fetch && r.ready.ffi;
const restrictSummary = (r: Awaited<ReturnType<typeof restrictRun>>): string =>
  JSON.stringify({ envSet: r.ready?.envSet, dyldRemoved: r.ready?.dyldRemoved, fetch: r.ready?.fetch, ffi: r.ready?.ffi, sysctlAnswered: r.read.answered, envReadable: r.read.env, exit: r.code });

async function main(): Promise<void> {
  console.log("=== compiled-binary proof: the Cowork channel's receiver thread ===");
  // Release-shaped: compile:core with a bundled-plugins manifest embedded the way a release build embeds one
  // (build-daemon.ts's MANIFEST_EMBED, a file outside src/). A plain compile once hid that the embed renamed every
  // Worker entry (compile:core's `--root src` is the fix this proves).
  const script = (JSON.parse(readFileSync(join(CLI_DIR, "package.json"), "utf8")) as { scripts: Record<string, string> }).scripts["compile:core"] ?? "";
  if (!script.includes("--define CLOVER_PLUGIN_RUN_PROBE=false") || !script.includes("--outfile ../../dist/clover-core")) throw new Error("compile:core no longer has the probe define or its outfile — update this gate");
  const releaseShaped = (line: string): string => line.replace("--outfile ../../dist/clover-core", `${MANIFEST_EMBED} --outfile ../../dist/clover-core`);
  const manifest = join(CLI_DIR, ...MANIFEST_EMBED.split("/"));
  mkdirSync(dirname(manifest), { recursive: true });
  writeFileSync(manifest, '{"format":1,"files":{}}\n');
  const buildEnv = { ...process.env, PATH: `${dirname(process.execPath)}:${process.env.PATH ?? ""}` };
  const scratch = mkdtempSync(join(tmpdir(), "clover-fd-receiver-proof-"));
  try {
    const compile = spawnSync("sh", ["-c", releaseShaped(script)], { cwd: CLI_DIR, encoding: "utf8", timeout: COMPILE_TIMEOUT_MS, env: buildEnv });
    if (compile.status !== 0) throw new Error(`compile:core (release-shaped) failed:\n${compile.stdout ?? ""}\n${compile.stderr ?? ""}`);
    if (!existsSync(DIST_BINARY)) throw new Error(`compile:core reported success but ${DIST_BINARY} was not produced`);
    const home = join(scratch, "home"); mkdirSync(home);
    const env: Record<string, string> = { PATH: process.env.PATH ?? "/usr/bin:/bin", HOME: process.env.HOME ?? homedir(), CLOVER_HOME: home, CLOVER_PROFILE: "dev", CLOVER_KEYCHAIN_SERVICE: "com.waifucave.clover.core.test-isolated", CLOVER_LOGIN_SHELL_PATH: "off" };
    const good = join(scratch, "clover-core");
    copyFileSync(DIST_BINARY, good); chmodSync(good, 0o755); sign(good);
    const run = await runChild(good, ["__fd-receiver-probe"], env, scratch);
    const result = parseProbe(run.stdout);
    if (run.code !== 0 || result?.ok !== true) throw new Error(`the compiled daemon's receiver thread did not start (exit ${run.code}): ${JSON.stringify(result)}\n${run.stderr.trim()}`);
    console.log(`ok: the probe line came back through the receiver hub (${JSON.stringify(result)})`);

    const adapter = await runChild(good, ["__host-code-adapter-probe"], env, scratch);
    const adapterResult = parseProbe(adapter.stdout);
    if (adapter.code !== 0 || adapterResult?.ok !== true) throw new Error(`the host-code broker's modules do not resolve inside the compiled daemon (exit ${adapter.code}): ${JSON.stringify(adapterResult)}\n${adapter.stderr.trim()}`);
    console.log(`ok: installedHostCodeAdapter() ran in the compiled daemon (${JSON.stringify(adapterResult)})`);

    const lazy = await runChild(good, ["__host-env-lazy-probe"], env, scratch);
    const lazyResult = parseProbe(lazy.stdout);
    if (lazy.code !== 0 || lazyResult?.ok !== true) throw new Error(`the lazy host-env require does not resolve inside the compiled daemon (exit ${lazy.code}): ${JSON.stringify(lazyResult)}\n${lazy.stderr.trim()}`);
    console.log(`ok: the activation seam's lazy host-env require resolved in the compiled daemon (${JSON.stringify(lazyResult)})`);

    const release = readFileSync(DIST_BINARY);
    const leaked = PROBE_MARKERS.filter((m) => release.includes(Buffer.from(m)));
    if (leaked.length > 0) throw new Error(`the release-shaped clover-core carries the plugin-run probe (${leaked.join(", ")}): CLOVER_PLUGIN_RUN_PROBE=false no longer removes it`);
    console.log("ok: the release-shaped binary has no plugin-run probe route");

    const probeDir = join(scratch, "probe-build"); mkdirSync(probeDir);
    const probeBuild = releaseShaped(script).replace("--define CLOVER_PLUGIN_RUN_PROBE=false", "--define CLOVER_PLUGIN_RUN_PROBE=true").replace("--outfile ../../dist/clover-core", `--outfile ${JSON.stringify(join(probeDir, "clover-core"))}`);
    const built = spawnSync("sh", ["-c", probeBuild], { cwd: CLI_DIR, encoding: "utf8", timeout: COMPILE_TIMEOUT_MS, env: buildEnv });
    if (built.status !== 0) throw new Error(`the probe build failed:\n${built.stdout ?? ""}\n${built.stderr ?? ""}`);
    const probeCore = join(probeDir, "clover-core"); chmodSync(probeCore, 0o755); sign(probeCore);
    // The dev profile's plugin Bun (the gate runs the core as dev): in the temp home's bin, signed under its own dev
    // identifier, its digest recorded beside it the way dev:daemon records it (#234's check 6, L2).
    const pluginBun = join(home, "bin", "clover-plugin-bun"); mkdirSync(dirname(pluginBun), { recursive: true });
    copyFileSync(realpathSync(process.execPath), pluginBun); chmodSync(pluginBun, 0o755);
    const signed = spawnSync("codesign", ["--force", "--sign", "-", "--identifier", PLUGIN_BUN_IDENTIFIER, "--options", PLUGIN_BUN_OPTIONS, "--entitlements", PLUGIN_BUN_ENTITLEMENTS, pluginBun], { encoding: "utf8" });
    if (signed.status !== 0) throw new Error(`codesign of ${pluginBun} failed: ${(signed.stderr ?? "").trim()}`);
    const digest = pluginBunDigest(pluginBun);
    if (digest === undefined) throw new Error(`no digest for ${pluginBun}`);
    writeFileSync(`${pluginBun}.digest`, `${digest}\n`);
    const pluginScratch = join(scratch, "plugin-run"); mkdirSync(pluginScratch);
    const pluginRun = await runChild(probeCore, ["__plugin-run-probe", pluginScratch], env, scratch);
    const pluginResult = parseProbe(pluginRun.stdout);
    if (pluginRun.code !== 0 || pluginResult?.ok !== true) throw new Error(`a plugin host did not run guarded on clover-plugin-bun inside the compiled core (exit ${pluginRun.code}): ${JSON.stringify(pluginResult)}\n${pluginRun.stderr.trim()}`);
    console.log(`ok: a plugin host ran on clover-plugin-bun, not clover-core, without BUN_BE_BUN, guarded, its outside import refused (${JSON.stringify(pluginResult)})`);

    const hostScratch = join(scratch, "plugin-host"); mkdirSync(hostScratch);
    const hostRun = await runChild(probeCore, ["__plugin-host-probe", hostScratch], env, scratch);
    const hostResult = parseProbe(hostRun.stdout);
    if (hostRun.code !== 0 || hostResult?.ok !== true) throw new Error(`the compiled core did not start a plugin-host process from its embedded bundles (exit ${hostRun.code}): ${JSON.stringify(hostResult)}\n${hostRun.stderr.trim()}`);
    console.log(`ok: the compiled core started a plugin-host process from its embedded bundles, and it answered pluginHost.ping (${JSON.stringify(hostResult)})`);

    // 4. The restrict flag: neither restricted process's environment is readable from here, and each still runs.
    if (!CORE_OPTIONS.includes("restrict") || !PLUGIN_BUN_OPTIONS.includes("restrict")) throw new Error("RESOURCE_BINARIES no longer signs the core and the plugin Bun with restrict: update this gate");
    const control = join(probeDir, "clover-core-runtime-only");
    copyFileSync(probeCore, control); chmodSync(control, 0o755); sign(control, "runtime");
    const open = await restrictRun([control, "__restrict-probe"], env, scratch);
    if (!probeWorked(open) || !open.read.env) throw new Error(`the control (hardened runtime alone) didn't run, or its environment wasn't readable, so the reading proves nothing: ${restrictSummary(open)}\n${open.stderr}`);
    console.log(`ok: the control, signed with the hardened runtime alone, has its environment read by another process of the user (${restrictSummary(open)})`);
    const core = await restrictRun([probeCore, "__restrict-probe"], env, scratch);
    if (!probeWorked(core) || core.read.env) throw new Error(`the core signed ${CORE_OPTIONS} didn't run its checks, or its environment was readable: ${restrictSummary(core)}\n${core.stderr}`);
    console.log(`ok: the core signed ${CORE_OPTIONS}: its environment isn't readable by another process of the user; it got the variable, Bun.serve + fetch and bun:ffi work (${restrictSummary(core)})`);
    const bunRun = await restrictRun([pluginBun, "--no-env-file", RESTRICT_PROBE_SCRIPT], env, scratch);
    if (!probeWorked(bunRun) || bunRun.read.env) throw new Error(`the plugin Bun signed ${PLUGIN_BUN_OPTIONS} didn't run its checks, or its environment was readable: ${restrictSummary(bunRun)}\n${bunRun.stderr}`);
    console.log(`ok: the plugin Bun signed ${PLUGIN_BUN_OPTIONS}: its environment isn't readable by another process of the user; it got the variable, Bun.serve + fetch and bun:ffi work (${restrictSummary(bunRun)})`);

    const broken = withBrokenEntry(readFileSync(DIST_BINARY));
    if (broken === null) throw new Error(`the binary does not contain the entry string ${ENTRY_NAME}: fd-channel.ts does not use the compiled entry`);
    const bad = join(scratch, "clover-core-broken");
    writeFileSync(bad, broken); chmodSync(bad, 0o755); sign(bad);
    const negative = await runChild(bad, ["__fd-receiver-probe"], env, scratch);
    if (parseProbe(negative.stdout)?.ok === true) throw new Error("negative control failed: a binary without the worker entry still passed the probe, so the probe proves nothing");
    console.log("ok: the negative control (entry renamed in a copy) is refused by the same probe");
  } finally {
    rmSync(scratch, { recursive: true, force: true });
    rmSync(manifest, { force: true });
  }
}

if (import.meta.main) main().catch((error) => { console.error(`verify:fd-receiver: ${(error as Error).message}`); process.exit(1); });

// Run-folder logging with redaction. Every record any probe writes passes through
// `Redactor.scrub`, so tokens, keys and e-mail addresses never reach the disk.
import { appendFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { join } from "node:path";

const SECRET_KEY =
  /(token|secret|password|passwd|api[-_]?key|authorization|cookie|credential|refresh|bearer|private[-_]?key|session[-_]?key)/i;

// Keys that look secret by name but hold harmless counts or flags in ACP / MCP.
const SAFE_KEYS = /^(inputTokens|outputTokens|totalTokens|cachedReadTokens|cachedWriteTokens|thoughtTokens|maxTokens|tokens|used|size|isAuthenticated)$/;

const PATTERNS: [RegExp, string][] = [
  [/eyJ[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}/g, "<redacted:jwt>"],
  [/\bBearer\s+[A-Za-z0-9._~+/=-]{8,}/gi, "Bearer <redacted>"],
  [/\b(sk|pk|rk)-[A-Za-z0-9_-]{16,}/g, "<redacted:key>"],
  [/\bAIza[0-9A-Za-z_-]{30,}/g, "<redacted:google-key>"],
  [/\bya29\.[0-9A-Za-z_-]{20,}/g, "<redacted:google-token>"],
  [/\b1\/\/[0-9A-Za-z_-]{20,}/g, "<redacted:google-refresh>"],
  [/\bgh[pousr]_[A-Za-z0-9]{20,}/g, "<redacted:github>"],
  [/\bkey_[A-Za-z0-9]{20,}/g, "<redacted:key>"],
  [/[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+(\.[A-Za-z0-9-]+)*\.[A-Za-z]{2,}/g, "<email>"],
];

export function sha12(value: string): string {
  return createHash("sha256").update(value).digest("hex").slice(0, 12);
}

export class Redactor {
  private secrets = new Map<string, string>();

  /** Registers a value generated by the probe (a bridge token, say) so it is never written. */
  add(secret: string, label: string): void {
    if (secret.length >= 6) this.secrets.set(secret, `<secret:${label}:sha256=${sha12(secret)}>`);
  }

  scrubString(s: string): string {
    let out = s;
    for (const [secret, mark] of this.secrets) out = out.split(secret).join(mark);
    for (const [re, mark] of PATTERNS) out = out.replace(re, mark);
    return out;
  }

  scrub(value: unknown, key?: string): unknown {
    if (typeof value === "string") {
      if (key && SECRET_KEY.test(key) && !SAFE_KEYS.test(key)) return value.length ? `<redacted:${sha12(value)}>` : "";
      return this.scrubString(value);
    }
    if (Array.isArray(value)) return value.map((v) => this.scrub(v));
    if (value && typeof value === "object") {
      const obj = value as Record<string, unknown>;
      // ACP's { name, value } pairs (env variables, HTTP headers).
      if (typeof obj.name === "string" && typeof obj.value === "string" && SECRET_KEY.test(obj.name)) {
        return { ...obj, value: `<redacted:${sha12(obj.value)}>` };
      }
      const out: Record<string, unknown> = {};
      for (const [k, v] of Object.entries(obj)) out[k] = this.scrub(v, k);
      return out;
    }
    return value;
  }
}

export class RunLog {
  readonly dir: string;
  readonly redactor: Redactor;
  private t0 = Date.now();

  constructor(dir: string, redactor = new Redactor()) {
    this.dir = dir;
    this.redactor = redactor;
    mkdirSync(dir, { recursive: true });
  }

  path(file: string): string {
    return join(this.dir, file);
  }

  /**
   * Appends one NDJSON record, scrubbed, stamped with the log's own milliseconds since the run
   * started. The stamp is written last, so a field of the record named `ms` can never override it.
   */
  write(file: string, record: Record<string, unknown>): void {
    const line = JSON.stringify({ ...(this.redactor.scrub(record) as object), ms: Date.now() - this.t0 });
    appendFileSync(this.path(file), line + "\n");
  }

  /** Appends raw text (stderr), scrubbed line by line. */
  text(file: string, chunk: string): void {
    appendFileSync(this.path(file), this.redactor.scrubString(chunk));
  }

  /** Appends `{ event, data }`: the data is nested, so its own fields (a tool's `kind`) can't relabel the event. */
  event(kind: string, data: Record<string, unknown> = {}): void {
    this.write("events.ndjson", { event: kind, data });
    const brief = JSON.stringify(this.redactor.scrub(data));
    console.log(`[${((Date.now() - this.t0) / 1000).toFixed(1)}s] ${kind} ${brief.length > 400 ? brief.slice(0, 400) + "…" : brief}`);
  }
}
